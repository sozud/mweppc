#!/usr/bin/env python3
"""The native 64-bit PS2 compiler: build/PS2_3_0_1/native/<arch>/mwccps2.

    native_ps2.py [--gen-only] [-j N] [--arch x86_64|arm64] [--asan] [--only UNIT]

1. Generates src/native/ps2/{exe_data,parser_tables,strings,compileroptions}.c from
   orig/PS2_3_0_1/mwccps2.exe with the PSP generators (tools/mwccpsp/gen_*.py),
   reading the PS2 copies of the tables. PS2 addresses come from config/PS2_3_0_1
   (ps2_map.ps2_address_map); unnamed addresses are written
   b210_func_/b210_data_XXXXXXXX (PS2 addresses), which native_glue.py binds.
2. Runs tools/mwccpsp/native_build.py --ps2: compiles every unit with
   clang and -DMWCCPS2=1, sorts the undefined symbols (aborting stubs for
   original code without source) and links.
"""

import argparse
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, "..", ".."))
PSP_TOP = os.path.join(REPO, "tools", "mwccpsp")
sys.path.insert(0, HERE)
sys.path.insert(0, PSP_TOP)
import ps2_map  # noqa: E402

EXE = os.path.join(REPO, "orig", "PS2_3_0_1", "mwccps2.exe")
DST = os.path.join(REPO, "src", "native", "ps2")


def ps2_names():
    """PS2 address -> one name for it, and name -> PS2 address"""
    addr, amap = ps2_map.ps2_address_map()
    by_va = {}
    # plain names before func_/data_XXXXXXXX ones; no Unit.c/static names
    for name in sorted(addr, key=lambda n: (n.startswith(("func_", "data_")), n)):
        if "/" in name or "$" in name:
            continue
        by_va.setdefault(addr[name], name)
    return by_va, addr, amap


def generate():
    by_va, addr, amap = ps2_names()
    os.makedirs(DST, exist_ok=True)

    import gen_native_data
    import gen_native_strings
    import gen_parser_psp

    overrides = {0x5CCB34: addr["char_ptr"]}

    def at(va):
        t = overrides.get(va) or amap(va)
        if t is None:
            sys.exit(f"no PS2 address for PSP 0x{va:08X}")
        return t

    gen_native_data.EXE = EXE
    gen_native_data.AT = at
    gen_native_data.SYMS = by_va
    gen_native_data.DST = os.path.join(DST, "exe_data.c")
    gen_native_data.PREFIX = "b210_"
    gen_native_data.VFPU = False  # PSP-only (the PS2 inline assembler has none)
    gen_native_data.main()
    roots = [(n, addr[n]) for n, _ in gen_parser_psp.ROOTS]
    g = gen_parser_psp.Gen(exe=EXE, syms=by_va, roots=roots, dst=os.path.join(DST, "parser_tables.c"), prefix="b210_")
    import contextlib
    import io

    with contextlib.redirect_stdout(io.StringIO()) as log:
        g.run()
    print(log.getvalue().splitlines()[0])
    gen_native_strings.main(exe=EXE, dst=os.path.join(DST, "strings.c"))
    gen_compileroptions(addr)


def gen_compileroptions(addr):
    """b210's #pragma table (CPrep.c's compileroptions: {name, bits}, bits =
    flags | copts offset). The offsets are b210's (x86) ones: past
    CompilerLinkerOptions.oldprefixname, the one pointer among the pragma
    fields, the native struct is 4 bytes further on, so they are written as
    NATIVE_OFF(offset)."""
    import struct

    from pe import PE

    pe = PE(EXE)
    va = addr["compileroptions"]
    rows = []
    while True:
        name, bits = struct.unpack("<IH", pe.read(va, 6))
        if not name:
            break
        text = pe.read(name, 128).split(b"\0")[0].decode("latin-1")
        rows.append(f'    {{"{text}", (short)(0x{bits & ~0x1FFF:04X} | NATIVE_OFF(0x{bits & 0x1FFF:03X}))}},')
        va += 8
    out = (
        [
            "// generated by tools/mwccps2/native_ps2.py from mwccps2.exe: do not edit",
            "// b210's #pragma table for the native build (CPrep.c declares it extern).",
            '#include "compiler/common.h"',
            '#include "compiler/CParser.h"',
            "#include <stddef.h>",
            "",
            "typedef struct CompilerOption {",
            "    char* name;",
            "    short bits;",
            "} CompilerOption;",
            "",
            "#define OLD offsetof(CompilerLinkerOptions, oldprefixname)",
            "#define NATIVE_OFF(o) ((o) < OLD + 4 ? (o) : (o) + (offsetof(CompilerLinkerOptions, inlinelevel) - (OLD + 4)))",
            "",
            "CompilerOption compileroptions[] = {",
        ]
        + rows
        + ["    {NULL, 0}", "};"]
    )
    dst = os.path.join(DST, "compileroptions.c")
    open(dst, "w").write("\n".join(out) + "\n")
    print(f"wrote {dst}: {len(rows)} pragmas")


def main():
    if ps2_map.PS2_BUILD != 210:
        # the generated tables, the b210_ names and build/mwccps2-native are b210's
        sys.exit(f"native_ps2.py builds b210 only (MWCCPS2_BUILD={ps2_map.PS2_BUILD})")
    ap = argparse.ArgumentParser()
    ap.add_argument("--gen-only", action="store_true")
    ap.add_argument("-j", type=int, default=1)
    ap.add_argument("--arch", default="arm64" if os.uname().machine in ("arm64", "aarch64") else "x86_64")
    ap.add_argument("--asan", action="store_true")
    ap.add_argument("--only", help="recompile only units whose path contains this")
    a = ap.parse_args()
    generate()
    if a.gen_only:
        return
    subprocess.run(
        [
            sys.executable,
            os.path.join(PSP_TOP, "native_build.py"),
            "--ps2",
            "-j",
            str(a.j),
            "--arch",
            a.arch,
            *(["--asan"] if a.asan else []),
            *(["--only", a.only] if a.only else []),
        ],
        check=True,
    )


if __name__ == "__main__":
    main()
