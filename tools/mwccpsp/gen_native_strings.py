#!/usr/bin/env python3
"""Generate src/native/strings.c: the exe's string table resources (RT_STRING)
for the native LoadStringA (3.0.1's COS_GetString reads its messages with it).

    gen_native_strings.py

A string table resource holds 16 strings: block N has ids (N-1)*16 .. +15,
each a UTF-16 length and its characters. Only the first language of each
block is used; the exe has one.
"""

import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOP = os.path.normpath(os.path.join(HERE, "..", ".."))
REPO = TOP
sys.path.insert(0, HERE)
from gen_parser_psp import literal  # noqa: E402
from pe import PE  # noqa: E402

RT_STRING = 6


def main(exe=None, dst=None):
    pe = PE(exe or os.path.join(REPO, "orig", "PSP_3_0_1", "mwccpsp.exe"))
    rva, _ = pe.dirs[2]
    base = pe.off(rva)
    d = pe.data

    def entries(off):
        named, ids = struct.unpack_from("<HH", d, base + off + 12)
        for i in range(named + ids):
            name, target = struct.unpack_from("<II", d, base + off + 16 + 8 * i)
            yield name, target

    strings = {}
    for typ, t in entries(0):
        if typ != RT_STRING:
            continue
        for block, b in entries(t & 0x7FFFFFFF):
            lang, leaf = next(entries(b & 0x7FFFFFFF))
            data_rva, size = struct.unpack_from("<II", d, base + leaf)
            o = pe.off(data_rva)
            p = 0
            for i in range(16):
                n = struct.unpack_from("<H", d, o + p)[0]
                p += 2
                if n:
                    text = bytes(d[o + p : o + p + 2 * n]).decode("utf-16-le")
                    strings[(block - 1) * 16 + i] = text
                p += 2 * n
    out = [
        "// generated by tools/mwccpsp/gen_native_strings.py from the 3.0.1 exe: do not edit",
        "// The string table resources, for the native LoadStringA.",
        "",
        "typedef struct NativeString {",
        "    unsigned int id;",
        "    const char* text;",
        "} NativeString;",
        "",
        f"const unsigned int native_string_count = {len(strings)};",
        "const NativeString native_strings[] = {",
    ]
    for k in sorted(strings):
        out.append(f"    {{{k}, {literal(strings[k].encode('latin-1', 'replace'))}}},")
    out.append("};")
    dst = dst or os.path.join(TOP, "src", "native", "strings.c")
    open(dst, "w").write("\n".join(out) + "\n")
    print(f"wrote {dst}: {len(strings)} strings")


if __name__ == "__main__":
    main()
