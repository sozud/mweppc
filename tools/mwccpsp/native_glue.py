#!/usr/bin/env python3
"""Sort the native build's undefined symbols.

    native_glue.py [--arch x86_64] [-v]

Links build/PSP_3_0_1/native/<arch>/obj/*.o, collects the undefined symbols and
sorts them:

  alias        a name (often func_XXXXXXXX) for an address where our source
               defines a function under another name: a linker alias
  code         original code we have no source for (not on the -O0/-Op path,
               or not yet written): a stub that aborts loudly
  bss          original zero-initialised data: a zeroed definition
  data         original initialised data: needs its contents
  host         no original address (Win32 API, MSL/libc): host shims

Writes the lists to build/PSP_3_0_1/native/<arch>/glue/*.txt.
"""

import argparse
import collections
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOP = os.path.normpath(os.path.join(HERE, "..", ".."))
REPO = TOP
sys.path.insert(0, HERE)
from pe import PE  # noqa: E402

import native  # noqa: E402

ARCH, ASAN = "x86_64", False


def load_addresses():
    addr = {}
    for f in ("symbols.manual.txt", "symbols.txt"):
        for line in open(os.path.join(TOP, "config", "PSP_3_0_1", f)):
            m = re.match(r"\s*([^\s=]+)\s*=\s*0x([0-9A-Fa-f]+);", line)
            if m:
                addr.setdefault(m.group(1), int(m.group(2), 16))
    return addr


DARWIN = sys.platform == "darwin"
# Mach-O prefixes C symbols with an underscore, ELF does not
PFX = "_" if DARWIN else ""
LINK = ["-lc++"] if DARWIN else ["-fuse-ld=lld", "-lstdc++", "-lm"]


def undefined(out, extra):
    objs = native.objects(ARCH, ASAN)
    args = ["clang", *native.arch_flags(ARCH), "-o", os.path.join(out, "mwccpsp"), *objs, *extra, *LINK]
    if not DARWIN:
        args.append("-Wl,--error-limit=0")
    p = subprocess.run(args, capture_output=True, text=True)
    if DARWIN:
        return sorted({m[1:] for m in re.findall(r'^  "(_[^"]+)", referenced from:', p.stderr, re.M)}), objs
    return sorted(set(re.findall(r"undefined symbol: ([A-Za-z_][\w$@?]*)", p.stderr))), objs


def defined(objs):
    p = subprocess.run(["nm", "-g", "--defined-only", *objs], capture_output=True, text=True)
    return {parts[2][len(PFX) :] for parts in (l.split() for l in p.stdout.splitlines()) if len(parts) == 3}


# Win32 calls the driver makes: shims in src/native/win32_posix.c
WIN32 = re.compile(
    r"^(Get|Set|Create|Delete|Find|Read|Write|Close|Load|Lock|Global|File|Format|System|Wait|"
    r"Remove|Sizeof|Ver|ShiftJIS_)\w*$"
)

# pointer-free initialised data copied byte for byte (same layout natively)
BYTES = re.compile(
    r"^st(bool|char|wchar|signedchar|unsignedchar|signedshort|unsignedshort|signedint|"
    r"unsignedint|signedlong|unsignedlong|signedlonglong|unsignedlonglong|float|shortdouble|"
    r"double|longdouble|int128)$"
)


BUILTINS = {"alloca"}


def write_glue(out, pe, cats, addr, secs):
    """glue.c: stubs and storage; ldflags.txt: ld -alias pairs"""
    known = sorted({va for va in addr.values()} | {int(x.split()[1], 16) for x in cats["bss"]})

    def gap(va):
        nxt = next((k for k in known if k > va), va + 0x100)
        return max(4, min(nxt - va, 0x10000))

    # no headers: some stub names collide with libc declarations
    lines = [
        "// generated by tools/mwccpsp/native_glue.py: do not edit",
        "",
        "extern long write(int fd, const void* buf, unsigned long n);",
        "static unsigned long len(const char* s) { unsigned long n = 0; while (s[n]) n++; return n; }",
        "static void unimplemented(const char* name) {",
        '    write(2, "mwccpsp (native): not implemented: ", 35);',
        "    write(2, name, len(name));",
        '    write(2, "\\n", 1);',
        "    __builtin_abort();",
        "}",
        "",
    ]
    for x in cats["code"]:
        name, va = x.split()
        lines.append(f'void {name}(void) {{ unimplemented("{name} (0x{va})"); }}')
    lines.append("")
    for x in cats["bss"]:
        name, va = x.split()
        # room for pointers that grow to 8 bytes
        lines.append(f"__attribute__((aligned(16))) unsigned char {name}[{gap(int(va, 16)) * 2}];")
    lines.append("")
    relocs = pe.relocations()
    for x in cats["data"]:
        name, va, sec = x.split()
        v = int(va, 16)
        n = gap(v)
        if BYTES.match(name):
            b = pe.read(v, 12)
            lines.append(f"__attribute__((aligned(4))) unsigned char {name}[12] = {{{', '.join(str(c) for c in b)}}};")
        elif not any(v <= r < v + n for r in relocs):
            # no pointers up to the next known symbol: the same bytes natively
            b = pe.read(v, n)
            lines.append(
                f"__attribute__((aligned(16))) unsigned char {name}[{n * 2}] = {{{', '.join(str(c) for c in b)}}};"
            )
        elif min(r for r in relocs if v <= r < v + n) - v >= 4:
            # pointers further on: the pointer-free start (enough for the
            # small variables just before a table)
            k = min(r for r in relocs if v <= r < v + n) - v
            b = pe.read(v, k)
            lines.append(f"// {name}: the {k} bytes before its first pointer")
            lines.append(
                f"__attribute__((aligned(16))) unsigned char {name}[{n * 2}] = {{{', '.join(str(c) for c in b)}}};"
            )
        else:
            lines.append(f"// TODO: {name} at 0x{va} has contents with pointers")
            lines.append(f"__attribute__((aligned(16))) unsigned char {name}[{gap(int(va, 16)) * 2}];")
    lines.append("")
    for name in cats["host"]:
        if WIN32.match(name):
            continue
        if name in BUILTINS:
            # a compiler builtin in C: define the symbol in assembly
            lines.append(f'__asm__(".globl {PFX}{name}\\n{PFX}{name}: ud2");')
            continue
        if name[0].islower() or name.startswith(("cobjc", "st")):
            lines.append(f"__attribute__((aligned(16))) unsigned char {name}[256]; // dead PPC/ObjC reference")
        else:
            lines.append(f'void {name}(void) {{ unimplemented("{name}"); }}')
    os.makedirs(os.path.join(out, "glue"), exist_ok=True)
    open(os.path.join(out, "glue", "glue.c"), "w").write("\n".join(lines) + "\n")
    open(os.path.join(out, "glue", "ldflags.txt"), "w").write(
        "".join(
            (
                f"-Wl,-alias,_{x.split()[1]},_{x.split()[0]}\n"
                if DARWIN
                else f"-Wl,--defsym={x.split()[0]}={x.split()[1]}\n"
            )
            for x in cats["alias"]
        )
    )


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--arch", default="x86_64")
    ap.add_argument("-v", action="store_true")
    ap.add_argument("--asan", action="store_true")
    a = ap.parse_args()
    global ARCH, ASAN
    ARCH, ASAN = a.arch, a.asan
    out = native.out_dir(a.arch, a.asan)
    pe = PE(os.path.join(REPO, "orig", "PSP_3_0_1", "mwccpsp.exe"))
    secs = [(n, pe.base + va, vs) for n, va, vs, raw, rs in pe.sections]

    def section(va):
        return next((n for n, s, vs in secs if s <= va < s + vs), "?")

    addr = load_addresses()
    und, objs = undefined(out, ["-fsanitize=address,undefined"] if a.asan else [])
    have = defined(objs)
    by_addr = collections.defaultdict(list)
    for name, va in addr.items():
        base = name.split("/")[-1]
        if base in have:
            by_addr[va].append(base)
    # our func_XXXXXXXX/data_XXXXXXXX definitions name their address
    for name in have:
        m = re.match(r"(?:data|func)_([0-9A-F]{8})$", name)
        if m and name not in by_addr[int(m.group(1), 16)]:
            by_addr[int(m.group(1), 16)].append(name)

    cats = collections.defaultdict(list)
    for u in und:
        m = re.match(r"(?:data|func)_([0-9A-F]{8})$", u)
        va = int(m.group(1), 16) if m else addr.get(u)
        if va is None:
            cats["host"].append(u)
        elif by_addr.get(va):
            cats["alias"].append(f"{u} {by_addr[va][0]}")
        elif section(va) == ".text":
            cats["code"].append(f"{u} {va:08X}")
        elif section(va) == ".bss":
            cats["bss"].append(f"{u} {va:08X}")
        else:
            cats["data"].append(f"{u} {va:08X} {section(va)}")

    # several undefined names for one address (a data_ name and the name our
    # source uses): one storage, the other names linker aliases of it
    for k in ("bss", "data"):
        first = {}
        keep = []
        for x in cats[k]:
            name, va = x.split()[:2]
            if va in first:
                cats["alias"].append(f"{name} {first[va]}")
            else:
                first[va] = name
                keep.append(x)
        cats[k] = keep

    write_glue(out, pe, cats, addr, secs)
    os.makedirs(os.path.join(out, "glue"), exist_ok=True)
    for k, v in cats.items():
        open(os.path.join(out, "glue", k + ".txt"), "w").write("\n".join(v) + "\n")
    print(f"{len(und)} undefined:", ", ".join(f"{k} {len(v)}" for k, v in sorted(cats.items())))
    if a.v:
        for k, v in sorted(cats.items()):
            print(k + ":", " ".join(x.split()[0] for x in v[:200]))


if __name__ == "__main__":
    main()
