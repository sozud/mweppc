#!/usr/bin/env python3
"""Sort the native build's undefined symbols.

    native_glue.py [--arch x86_64] [-v] [--ps2]

Links build/PSP_3_0_1/native/<arch>/obj/*.o, collects the undefined symbols and
sorts them:

  alias        a name (often func_XXXXXXXX) for an address where our source
               defines a function under another name: a linker alias
  code         original code we have no source for (not on the -O0/-Op path,
               or not yet written): a stub that aborts loudly
  bss          original zero-initialised data: a zeroed definition
  data         original initialised data: needs its contents
  host         no original address (Win32 API, MSL/libc): host shims

Writes the lists to build/PSP_3_0_1/native/<arch>/glue/*.txt.

--ps2: the PS2 build (build/PS2_3_0_1/native/). Names get the PS2 addresses
config/PS2_3_0_1 gives them (tools/mwccps2/ps2_map.py's
ps2_address_map: moved PSP names, derived and hand-derived PS2 addresses;
func_/data_XXXXXXXX names carry PSP addresses and move through the address
map; b210_func_/b210_data_XXXXXXXX name a PS2 address directly), and data
comes from orig/PS2_3_0_1/mwccps2.exe.
"""

import argparse
import collections
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOP = os.path.normpath(os.path.join(HERE, "..", ".."))
REPO = TOP
sys.path.insert(0, HERE)
from pe import PE  # noqa: E402

import native  # noqa: E402

ARCH, ASAN = "x86_64", False


def load_addresses():
    if native.PS2:
        return load_addresses_ps2()
    addr = {}
    for f in ("symbols.manual.txt", "symbols.txt"):
        for line in open(os.path.join(TOP, "config", "PSP_3_0_1", f)):
            m = re.match(r"\s*([^\s=]+)\s*=\s*0x([0-9A-Fa-f]+);", line)
            if m:
                addr.setdefault(m.group(1), int(m.group(2), 16))
    return addr


AMAP = None
HEX_NAME = re.compile(r"(?:data|func)_([0-9A-F]{8})$")
B210_NAME = re.compile(r"b210_(?:data|func)_([0-9A-F]{8})$")


def load_addresses_ps2():
    global AMAP
    sys.path.insert(0, os.path.join(REPO, "tools", "mwccps2"))
    import ps2_map  # noqa: E402

    addr, AMAP = ps2_map.ps2_address_map()
    return {k: v for k, v in addr.items()}


def address_of(name, addr):
    """the original address of `name`, or None"""
    if native.PS2:
        m = B210_NAME.match(name)
        if m:
            return int(m.group(1), 16)
        if name in addr:
            return addr[name]
        m = HEX_NAME.match(name)
        return AMAP(int(m.group(1), 16)) if m else None
    m = HEX_NAME.match(name)
    return int(m.group(1), 16) if m else addr.get(name)


DARWIN = sys.platform == "darwin"
# Mach-O prefixes C symbols with an underscore, ELF does not
PFX = "_" if DARWIN else ""
LINK = ["-lc++"] if DARWIN else ["-fuse-ld=lld", "-lstdc++", "-lm"]


def undefined(out, extra):
    objs = native.objects(ARCH, ASAN)
    args = ["clang", *native.arch_flags(ARCH), "-o", os.path.join(out, native.name()), *objs, *extra, *LINK]
    if not DARWIN:
        args.append("-Wl,--error-limit=0")
    p = subprocess.run(args, capture_output=True, text=True)
    if DARWIN:
        return sorted({m[1:] for m in re.findall(r'^  "(_[^"]+)", referenced from:', p.stderr, re.M)}), objs
    return sorted(set(re.findall(r"undefined symbol: ([A-Za-z_][\w$@?]*)", p.stderr))), objs


def defined(objs):
    p = subprocess.run(["nm", "-g", "--defined-only", *objs], capture_output=True, text=True)
    return {parts[2][len(PFX) :] for parts in (l.split() for l in p.stdout.splitlines()) if len(parts) == 3}


# Win32 calls the driver makes: shims in src/native/win32_posix.c
WIN32 = re.compile(
    r"^(Get|Set|Create|Delete|Find|Read|Write|Close|Load|Lock|Global|File|Format|System|Wait|"
    r"Remove|Sizeof|Ver|ShiftJIS_)\w*$"
)

# pointer-free initialised data copied byte for byte (same layout natively)
BYTES = re.compile(
    r"^st(bool|char|wchar|signedchar|unsignedchar|signedshort|unsignedshort|signedint|"
    r"unsignedint|signedlong|unsignedlong|signedlonglong|unsignedlonglong|float|shortdouble|"
    r"double|longdouble|int128)$"
)


BUILTINS = {"alloca"}


def write_glue(out, pe, cats, addr, secs):
    """glue.c: stubs and storage; ldflags.txt: ld -alias pairs"""
    known = sorted({va for va in addr.values()} | {int(x.split()[1], 16) for x in cats["bss"]})

    def gap(va):
        nxt = next((k for k in known if k > va), va + 0x100)
        return max(4, min(nxt - va, 0x10000))

    def room(n):
        # the storage for n original bytes. The next known address is not
        # always the end of the object (data_00625424 is data_0062541C + 8,
        # and natively data_0062541C[7] is 168 bytes, not 16): the PS2 build
        # gives every object at least 2 KB so none overruns its neighbour
        return max(n * 2, 2048) if native.PS2 else n * 2

    # no headers: some stub names collide with libc declarations
    lines = [
        "// generated by tools/mwccpsp/native_glue.py: do not edit",
        "",
        "extern long write(int fd, const void* buf, unsigned long n);",
        "static unsigned long len(const char* s) { unsigned long n = 0; while (s[n]) n++; return n; }",
        "static void unimplemented(const char* name) {",
        f'    write(2, "{native.name()} (native): not implemented: ", {len(native.name()) + 35 - 7});',
        "    write(2, name, len(name));",
        '    write(2, "\\n", 1);',
        "    __builtin_abort();",
        "}",
        "",
    ]
    for x in cats["code"]:
        name, va = x.split()
        lines.append(f'void {name}(void) {{ unimplemented("{name} (0x{va})"); }}')
    lines.append("")
    for x in cats["bss"]:
        name, va = x.split()
        # room for pointers that grow to 8 bytes
        lines.append(f"__attribute__((aligned(16))) unsigned char {name}[{room(gap(int(va, 16)))}];")
    lines.append("")
    relocs = pe.relocations()
    for x in cats["data"]:
        name, va, sec = x.split()
        v = int(va, 16)
        n = gap(v)
        if BYTES.match(name):
            b = pe.read(v, 12)
            lines.append(f"__attribute__((aligned(4))) unsigned char {name}[12] = {{{', '.join(str(c) for c in b)}}};")
        elif not any(v <= r < v + n for r in relocs):
            # no pointers up to the next known symbol: the same bytes natively
            b = pe.read(v, n)
            lines.append(
                f"__attribute__((aligned(16))) unsigned char {name}[{room(n)}] = {{{', '.join(str(c) for c in b)}}};"
            )
        elif min(r for r in relocs if v <= r < v + n) - v >= 4:
            # pointers further on: the pointer-free start (enough for the
            # small variables just before a table)
            k = min(r for r in relocs if v <= r < v + n) - v
            b = pe.read(v, k)
            lines.append(f"// {name}: the {k} bytes before its first pointer")
            lines.append(
                f"__attribute__((aligned(16))) unsigned char {name}[{room(n)}] = {{{', '.join(str(c) for c in b)}}};"
            )
        else:
            lines.append(f"// TODO: {name} at 0x{va} has contents with pointers")
            lines.append(f"__attribute__((aligned(16))) unsigned char {name}[{room(gap(int(va, 16)))}];")
    lines.append("")
    for name in cats["host"]:
        if WIN32.match(name):
            continue
        if name in BUILTINS:
            # a compiler builtin in C: define the symbol in assembly
            lines.append(f'__asm__(".globl {PFX}{name}\\n{PFX}{name}: ud2");')
            continue
        if native.PS2 and HEX_NAME.match(name) and name.startswith("func_"):
            # a PSP address with no PS2 twin in the address map
            lines.append(f'void {name}(void) {{ unimplemented("{name} (no PS2 address)"); }}')
            continue
        if name[0].islower() or name.startswith(("cobjc", "st")):
            lines.append(f"__attribute__((aligned(16))) unsigned char {name}[256]; // dead PPC/ObjC reference")
        else:
            lines.append(f'void {name}(void) {{ unimplemented("{name}"); }}')
    os.makedirs(os.path.join(out, "glue"), exist_ok=True)
    open(os.path.join(out, "glue", "glue.c"), "w").write("\n".join(lines) + "\n")
    open(os.path.join(out, "glue", "ldflags.txt"), "w").write(
        "".join(
            (
                f"-Wl,-alias,_{x.split()[1]},_{x.split()[0]}\n"
                if DARWIN
                else f"-Wl,--defsym={x.split()[0]}={x.split()[1]}\n"
            )
            for x in cats["alias"]
        )
    )


def overlap_warnings(cats, addr, have, objs):
    """undefined data names that point inside another object: natively each
    gets its own storage, where the exe (and the hybrid) has one. The extent
    of an object is its x86 size: a definition's from the PS2-layout
    CodeWarrior object (build/mwccps2/obj), an extern array's from its
    declaration (`extern T name[N]`, 4 bytes an element unless T is a
    byte/short type)."""
    import glob

    sys.path.insert(0, os.path.join(REPO, "tools", "mwccps2", "harness"))
    ext = {}  # name -> (start, size)
    try:
        import coff

        for path in glob.glob(os.path.join(REPO, "build", "mwccps2", "obj", "*.obj")):
            o = coff.Object(path)
            by_sec = collections.defaultdict(list)
            for sym in o.symbols.values():
                if sym.defined and sym.cls == 2 and not o.section(sym.section).code:
                    by_sec[sym.section].append(sym)
            for sec, syms in by_sec.items():
                syms.sort(key=lambda x: x.value)
                size = o.section(sec).size
                for i, sym in enumerate(syms):
                    end = syms[i + 1].value if i + 1 < len(syms) else size
                    n = sym.name[1:] if sym.name.startswith("_") else sym.name
                    va = address_of(n, addr)
                    if va is not None and end > sym.value:
                        ext[n] = (va, end - sym.value)
    except Exception as e:  # no CodeWarrior build: declarations only
        print(f"overlap check: no CW objects ({e})")
    small = re.compile(r"\b(char|UInt8|SInt8|Boolean|u8|s8|short|UInt16|SInt16)\b")
    for f in glob.glob(os.path.join(TOP, "src", "**", "*.c"), recursive=True) + glob.glob(
        os.path.join(TOP, "include", "**", "*.h"), recursive=True
    ):
        if "/native/" in f:
            continue
        for m in re.finditer(
            r"^\s*extern\s+([\w\s\*]+?)\s*\b(\w+)\s*\[\s*(0x[0-9A-Fa-f]+|\d+)\s*\]",
            open(f, errors="replace").read(),
            re.M,
        ):
            t, n, k = m.group(1), m.group(2), int(m.group(3), 0)
            va = address_of(n, addr)
            if va is not None and n not in ext and k > 1:
                ext[n] = (va, k * (2 if "short" in t or "16" in t else 1 if small.search(t) else 4))
    spans = sorted((va, va + size, n) for n, (va, size) in ext.items())
    starts = [x[0] for x in spans]
    import bisect

    for k in ("bss", "data"):
        for x in cats[k]:
            name, va = x.split()[0], int(x.split()[1], 16)
            i = bisect.bisect_right(starts, va) - 1
            while i >= 0 and spans[i][0] > va - 0x10000:
                s0, e0, n0 = spans[i]
                if s0 < va < e0 and n0 != name:
                    print(
                        f"warning: {name} (0x{va:08X}) is inside {n0} (0x{s0:08X}, {e0 - s0} bytes): separate storage natively"
                    )
                    break
                i -= 1


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--arch", default="x86_64")
    ap.add_argument("-v", action="store_true")
    ap.add_argument("--asan", action="store_true")
    ap.add_argument("--ps2", action="store_true")
    a = ap.parse_args()
    native.configure(a.ps2)
    global ARCH, ASAN
    ARCH, ASAN = a.arch, a.asan
    out = native.out_dir(a.arch, a.asan)
    pe = PE(native.exe_path())
    secs = [(n, pe.base + va, vs) for n, va, vs, raw, rs in pe.sections]

    def section(va):
        return next((n for n, s, vs in secs if s <= va < s + vs), "?")

    addr = load_addresses()
    und, objs = undefined(out, ["-fsanitize=address,undefined"] if a.asan else [])
    have = defined(objs)
    by_addr = collections.defaultdict(list)
    for name, va in addr.items():
        base = name.split("/")[-1]
        if base in have:
            by_addr[va].append(base)
    # our func_XXXXXXXX/data_XXXXXXXX definitions name their address
    for name in have:
        m = HEX_NAME.match(name) or B210_NAME.match(name)
        va = address_of(name, addr) if m else None
        if va is not None and name not in by_addr[va]:
            by_addr[va].append(name)

    cats = collections.defaultdict(list)
    for u in und:
        va = address_of(u, addr)
        if va is None:
            cats["host"].append(u)
        elif by_addr.get(va):
            cats["alias"].append(f"{u} {by_addr[va][0]}")
        elif section(va) == ".text":
            cats["code"].append(f"{u} {va:08X}")
        elif section(va) == ".bss":
            cats["bss"].append(f"{u} {va:08X}")
        else:
            cats["data"].append(f"{u} {va:08X} {section(va)}")

    # several undefined names for one address (a data_ name and the name our
    # source uses): one storage, the other names linker aliases of it
    for k in ("bss", "data"):
        first = {}
        keep = []
        for x in cats[k]:
            name, va = x.split()[:2]
            if va in first:
                cats["alias"].append(f"{name} {first[va]}")
            else:
                first[va] = name
                keep.append(x)
        cats[k] = keep

    # two of our own data definitions at one original address are two
    # storages natively where the exe (and the hybrid) has one
    if native.PS2:
        p = subprocess.run(["nm", "-g", "--defined-only", *objs], capture_output=True, text=True)
        data_at = collections.defaultdict(set)
        for parts in (l.split() for l in p.stdout.splitlines()):
            if len(parts) == 3 and parts[1] in "DSB":
                n = parts[2][len(PFX) :]
                va = address_of(n, addr)
                if va is not None:
                    data_at[va].add(n)
        for va, ns in sorted(data_at.items()):
            if len(ns) > 1:
                print(f"warning: one address 0x{va:08X}, separate definitions: {' '.join(sorted(ns))}")
    if native.PS2:
        overlap_warnings(cats, addr, have, objs)
    write_glue(out, pe, cats, addr, secs)
    os.makedirs(os.path.join(out, "glue"), exist_ok=True)
    for k, v in cats.items():
        open(os.path.join(out, "glue", k + ".txt"), "w").write("\n".join(v) + "\n")
    print(f"{len(und)} undefined:", ", ".join(f"{k} {len(v)}" for k, v in sorted(cats.items())))
    if a.v:
        for k, v in sorted(cats.items()):
            print(k + ":", " ".join(x.split()[0] for x in v[:200]))


if __name__ == "__main__":
    main()
