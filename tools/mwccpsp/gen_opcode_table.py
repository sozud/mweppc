#!/usr/bin/env python3
"""Generate src/psp/backend/OpcodeTable.c from mwccpsp.exe.

    gen_opcode_table.py > tools/mwccpsp/src/psp/backend/OpcodeTable.c

The opcode table initializer (0x46FFB0; it continues past 0x475E20, which
functions.csv splits off at padding, up to 0x478E30) is straight-line code:
about 900 calls to the opcode definers with constant arguments, ORs into the
table, and a few branches on the options. This transliterates it. A
"binary string" parse the original inlines (a macro over a literal like
"0000...1111") is folded to its value here; the result is the same.
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOP = os.path.normpath(os.path.join(HERE, "..", ".."))
REPO = TOP
sys.path.insert(0, HERE)
import capstone  # noqa: E402
from pe import PE  # noqa: E402

START, END = 0x46FFB0, 0x478E30
TABLE = 0x6115F8  # OpcodeDef data_006115F8[], 0x30 bytes each
FIELDS = {0x18: "flags", 0x1C: "flags2", 0x20: "intrinsic", 0x24: "unk24", 0x10: "unk10", 0x28: "unk28"}
COPTS = 0x6250C0
CALLS = {0x478ED0: "func_00478ED0", 0x478E30: "func_00478E30"}


HEADER = """#include "compiler/common.h"
#include <string.h>
#include "compiler/CParser.h"

// mwccpsp 3.0.1 opcode table (0x46FFB0..0x478E30), generated by
// tools/mwccpsp/gen_opcode_table.py from the original: every opcode's name, operand
// format, encoding and flags, with the choices that depend on the options.
// Do not edit by hand; regenerate.

typedef struct OpcodeDef {
    char* name;
    char* alias;
    char* format;
    UInt8 nargs;
    UInt8 size;
    UInt8 pad0E[2];
    UInt32 unk10;
    UInt8 pad14[4];
    UInt32 flags;
    UInt32 flags2;
    char* intrinsic;
    SInt32 unk24;
    SInt32 unk28;
    UInt16 unk2C;
} OpcodeDef;

extern OpcodeDef data_006115F8[];
extern SInt32 data_005EFC18;
extern void func_00478E30(int op, char* name, char* format, UInt16 real, UInt16 alt, UInt16 unk2C);
extern void func_00478ED0(int op, char* name, char* format, UInt32 unk10, UInt32 flags, char* intrinsic, SInt32 unk28, UInt16 unk2C);
"""


def copts_fields():
    """offset -> (type, name) from include/compiler/CParser.h (3.0.1 layout)"""
    hdr = open(os.path.join(TOP, "include", "compiler", "CParser.h")).read()
    body = hdr[hdr.index("#if MWCCPSP\nstruct CompilerLinkerOptions") :]
    out = {}
    for m in re.finditer(r"^\s+(\w[\w ]*?)\s+(\w+)(\[\d+\])?;\s+// 0x([0-9a-f]+)", body, re.M):
        out[int(m.group(4), 16)] = (m.group(1), m.group(2))
    return out


def main():
    pe = PE(os.path.join(REPO, "orig", "PSP_3_0_1", "mwccpsp.exe"))
    cs = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
    ins = list(cs.disasm(pe.read(START, END - START), START))
    co = copts_fields()

    def cstr(addr):
        try:
            b = pe.read(addr, 256).split(b"\0")[0]
        except Exception:
            return None
        if not all(32 <= c < 127 for c in b):
            return None
        return '"' + b.decode().replace("\\", "\\\\").replace('"', '\\"') + '"'

    def imm(v):
        if 0x5A0000 <= v < 0x600000:
            s = cstr(v)
            if s is not None:
                return s
        return f"{v:#x}" if v > 9 else str(v)

    def copt(addr, width):
        off = addr - COPTS
        if off in co:
            return f"copts.{co[off][1]}"
        base = max(o for o in co if o < off)  # inside an unknown[] gap
        return f"copts.{co[base][1]}[{off - base}]"

    targets = set()
    for i in ins:
        if i.mnemonic.startswith("j"):
            targets.add(int(i.op_str, 16))
    out = []
    emit = out.append
    args = []
    regs = {}
    k = 0
    skip = set()
    while k < len(ins):
        i = ins[k]
        a = i.address
        if a in skip:
            k += 1
            continue
        m, op = i.mnemonic, i.op_str
        if a in targets:
            assert not args, hex(a)
            emit(f"L{a - START:x}:")
        if m == "nop" or (m == "lea" and op == "eax, [eax]") or (m == "mov" and op == "eax, eax"):
            k += 1
            continue
        if m == "xor" and op == "eax, eax" and a < START + 0x10:
            k += 1
            continue  # memset setup
        if m == "mov" and op in ("edi, 0x6115f8", "ecx, 0x453c") and a < START + 0x10:
            k += 1
            continue
        if m == "rep stosd":
            emit("    memset(data_006115F8, 0, 0x5C5 * sizeof(OpcodeDef)); // 0x453C words in 3.0.1")
        elif m == "push" and re.fullmatch(r"0x[0-9a-f]+|\d+", op):
            args.append(imm(int(op, 0)))
        elif m == "push" and op == "edi" and a == START:
            pass  # prologue
        elif m == "push" and op in ("eax", "ebx", "ecx", "edx", "esi", "edi", "ebp"):
            args.append(f"r_{op}")
        elif m == "call":
            t = int(op, 16)
            emit(f"    {CALLS[t]}({', '.join(reversed(args))});")
            nargs = len(args)
            args = []
            for d in range(1, 4):  # the stack cleanup may be scheduled a little later
                nx = ins[k + d]
                if nx.mnemonic == "add" and nx.op_str == f"esp, {nargs * 4:#x}":
                    skip.add(nx.address)
                    break
            else:
                raise SystemExit(f"no cleanup after the call at {a:#x}")
            k += 1
            continue
        elif m == "or" and op.startswith("dword ptr [0x"):
            mm = re.fullmatch(r"dword ptr \[(0x[0-9a-f]+)\], (0x[0-9a-f]+|\d+)", op)
            addr, v = int(mm.group(1), 16), int(mm.group(2), 0)
            n, f = divmod(addr - TABLE, 0x30)
            emit(f"    data_006115F8[{n:#x}].{FIELDS[f]} |= {v:#x};")
        elif m == "mov" and op.startswith("dword ptr [0x"):
            mm = re.fullmatch(r"dword ptr \[(0x[0-9a-f]+)\], (0x[0-9a-f]+|\d+)", op)
            addr, v = int(mm.group(1), 16), int(mm.group(2), 0)
            if addr == 0x5EFC18:
                emit(f"    data_005EFC18 = {v:#x};")
            else:
                n, f = divmod(addr - TABLE, 0x30)
                name = {0x0: "name", 0x4: "alias", 0x8: "format"}.get(f) or FIELDS[f]
                cast = "(char*)" if name in ("name", "alias", "format") else ""
                emit(f"    data_006115F8[{n:#x}].{name} = {cast}{imm(v)};")
        elif m == "mov" and re.fullmatch(r"(e[a-d]x|e[ds]i), (0x[0-9a-f]+)", op):
            r, v = op.split(", ")
            v = int(v, 16)
            s = cstr(v)
            nx = ins[k + 1]
            if s is not None and nx.mnemonic == "movzx" and nx.op_str.endswith(f"byte ptr [{r}]"):
                # an inlined binary-string parse: find its exit and the result register
                b = pe.read(v, 64).split(b"\0")[0]
                val = 0
                for c in b:
                    val = val * 2 + (c - 0x30)
                acc = next(x.op_str.split(",")[0] for x in ins[k : k + 6] if x.mnemonic == "xor")  # xor acc, acc
                j = k
                while not (
                    ins[j].mnemonic == "jmp" or (ins[j].mnemonic == "jne" and ins[j + 1].mnemonic != "jmp" and False)
                ):
                    j += 1
                    if (
                        ins[j].mnemonic == "jne"
                        and int(ins[j].op_str, 16) < ins[j].address
                        and ins[j + 1].mnemonic != "jmp"
                    ):
                        break
                exit_ = None
                for x in ins[k : j + 2]:
                    if x.mnemonic == "je":
                        exit_ = int(x.op_str, 16)
                regs[acc] = f"r_{acc}"
                emit(f"    r_{acc} = {val:#x}; // {b.decode()}")
                if ins[j].mnemonic == "jmp":
                    emit(f"    goto L{exit_ - START:x};")
                    k = j + 1
                else:
                    k = j + 1  # falls through to the exit
                continue
            emit(f"    r_{r} = {v:#x};")
            regs[r] = f"r_{r}"
        elif m == "movzx" and re.fullmatch(r"(e[a-d]x|e[ds]i), (di|si)", op):
            r, src = op.split(", ")
            emit(f"    r_{r} = (UInt16)r_e{src};")
        elif m in ("cmp", "test", "movsx"):
            # option tests feeding a branch
            if m == "movsx":
                mm = re.fullmatch(r"(e[a-d]x), byte ptr \[(0x[0-9a-f]+)\]", op)
                regs[mm.group(1)] = copt(int(mm.group(2), 16), 1)
                k += 1
                continue
            j = ins[k + 1]
            if m == "cmp":
                mm = re.fullmatch(r"(byte|word) ptr \[(0x[0-9a-f]+)\], (\d+)", op)
                lhs, rhs = copt(int(mm.group(2), 16), 1), mm.group(3)
                rel = {"jl": "<", "jge": ">=", "jne": "!=", "je": "=="}[j.mnemonic]
                cond = f"{lhs} {rel} {rhs}"
            else:
                r, mask = op.split(", ")
                expr = regs[r] if mask == r else f"({regs[r]} & {mask})"
                cond = f"{expr} {'!=' if j.mnemonic == 'jne' else '=='} 0"
            emit(f"    if ({cond}) {{\n        goto L{int(j.op_str, 16) - START:x};\n    }}")
            k += 2
            continue
        elif m == "jmp":
            emit(f"    goto L{int(op, 16) - START:x};")
        elif m in ("pop", "ret"):
            if m == "ret":
                emit("    return;")
        elif m == "push" and op == "edi":
            pass
        else:
            raise SystemExit(f"unhandled {hex(a)}: {m} {op}")
        k += 1
    print(HEADER)
    print("void func_0046FFB0(void) {")
    print("    UInt32 r_eax, r_ecx, r_edx, r_edi;\n")
    print("\n".join(out))
    print("}")


if __name__ == "__main__":
    main()
