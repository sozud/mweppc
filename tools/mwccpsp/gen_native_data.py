#!/usr/bin/env python3
"""Generate src/native/exe_data.c: initialised data with pointers that our
source declares extern (the hybrid build uses the exe's copies), written as
typed 64-bit C for the native build.

    gen_native_data.py

Tables:
  char_ptr       0x5CCB34  TypePointer to stchar
  data_005CBED8  0x5CBED8  runtime routines {name, flags, type, object}[16]
  data_005CEE74  0x5CEE74  inline assembler VFPU constants {name, value}[38]
  data_005CED74  0x5CED74  inline assembler VFPU conditions {name, value}[32]
  data_005D0140  0x5D0140  instruction selection by ENode type (83 functions)
  IRO_StdFuncs   0x5D3468  the optimizer's C library descriptors (480) and headers

References are bound with asm labels so no header types get in the way.
"""

import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOP = os.path.normpath(os.path.join(HERE, "..", ".."))
REPO = TOP
sys.path.insert(0, HERE)
from gen_parser_psp import literal, load_symbols  # noqa: E402
from pe import PE  # noqa: E402

# the PS2 build (tools/mwccps2/native_ps2.py) sets these: its exe,
# the PS2 address of each PSP address below, PS2 address -> name, the output,
# the prefix of unnamed addresses, and whether the VFPU tables exist
EXE = os.path.join(REPO, "orig", "PSP_3_0_1", "mwccpsp.exe")
AT = None
SYMS = None
DST = os.path.join(TOP, "src", "native", "exe_data.c")
PREFIX = ""
VFPU = True


def main():
    pe = PE(EXE)
    syms = SYMS if SYMS is not None else load_symbols()
    at = AT or (lambda va: va)
    relocs = pe.relocations()
    refs = {}

    def u32(va):
        return struct.unpack("<I", pe.read(va, 4))[0]

    def cstr(va):
        return literal(pe.read(va, 256).split(b"\0")[0]) if va else "NULL"

    def ref(va, kind):
        if not va:
            return "NULL"
        name = syms.get(va) or (f"{PREFIX}func_{va:08X}" if kind == "func" else f"{PREFIX}data_{va:08X}")
        ident = "r_" + name.replace("$", "_")
        refs[ident] = (name, kind)
        return f"(void*){ident}" if kind == "data" else ident

    out = [
        "// generated by tools/mwccpsp/gen_native_data.py from the 3.0.1 exe: do not edit",
        "// Initialised data with pointers for the native build (see the script).",
        "#include <stddef.h>",
        "",
        "#ifdef __APPLE__",
        '#define SYM(name) "_" name',
        "#else",
        "#define SYM(name) name",
        "#endif",
        "",
    ]
    body = []

    # TypePointer {TypeType type; SInt32 size; Type* target; UInt32 qual}
    cp = at(0x5CCB34)
    t, size, target, qual = pe.read(cp, 1)[0], u32(cp + 4), u32(cp + 8), u32(cp + 12)
    body.append(
        "struct { unsigned char type; int size; void* target; unsigned int qual; } "
        f'char_ptr_def __asm__(SYM("char_ptr")) = {{{t}, {size}, {ref(target, "data")}, {qual}}};'
    )
    body.append("")

    # stvoid is a Type, but 3.0.1 also reads it as a TypeIntegral (in .bss, so
    # zeros follow it); natively it gets zero padding
    body.append(
        'struct { unsigned char type; int size; unsigned char pad[24]; } stvoid_def __asm__(SYM("stvoid")) = '
        "{0, 0, {0}};"
    )
    body.append("")

    rows = []
    for i in range(16):
        e = at(0x5CBED8) + 16 * i
        rows.append(f"    {{{cstr(u32(e))}, 0x{u32(e + 4):X}, {ref(u32(e + 8), 'data')}, {ref(u32(e + 12), 'data')}}},")
    body.append(
        "struct { char* name; unsigned int flags; void* type; void* object; } "
        'runtime_routines[16] __asm__(SYM("data_005CBED8")) = {'
    )
    body += rows
    body.append("};")
    body.append("")

    for va, n in ((0x5CEE74, 38), (0x5CED74, 32)) if VFPU else ():
        rows = [
            f"    {{{cstr(u32(at(va) + 8 * i))}, {struct.unpack('<i', pe.read(at(va) + 8 * i + 4, 4))[0]}}},"
            for i in range(n)
        ]
        body.append(f'struct {{ char* name; int value; }} named_{va:08X}[{n}] __asm__(SYM("data_{va:08X}")) = {{')
        body += rows
        body.append("};")
        body.append("")

    # the optimizer's C library descriptors: {name, header, handler, evaluate}
    # sorted by name; the headers {name, enabled} are only reached through them
    hbase, hend = at(0x5D33A8), at(0x5D3468)
    nh = (hend - hbase) // 8
    body.append(f"static struct {{ char* name; unsigned char enabled; }} iro_headers[{nh}] = {{")
    body += [f"    {{{cstr(u32(hbase + 8 * i))}, {pe.read(hbase + 8 * i + 4, 1)[0]}}}," for i in range(nh)]
    body.append("};")
    rows = []
    for i in range(480):
        e = hend + 16 * i
        h = u32(e + 4)
        hdr = f"&iro_headers[{(h - hbase) // 8}]" if h else "NULL"
        rows.append(
            f"    {{{cstr(u32(e))}, {hdr}, (void*){ref(u32(e + 8), 'func')}, (void*){ref(u32(e + 12), 'func')}}},"
        )
    body.append(
        "struct { char* name; void* header; void* handler; void* evaluate; } "
        'iro_stdfuncs[480] __asm__(SYM("IRO_StdFuncs")) = {'
    )
    body += rows
    body.append("};")
    body.append("")

    va, n = at(0x5D0140), 0
    while va + 4 * n in relocs:
        n += 1
    fns = [ref(u32(va + 4 * i), "func") for i in range(n)]
    body.append(f'void* isel_by_type[{n}] __asm__(SYM("data_005D0140")) = {{')
    body += [f"    (void*){f}," for f in fns]
    body.append("};")

    for ident, (name, kind) in sorted(refs.items()):
        if kind == "data":
            out.append(f'extern unsigned char {ident}[] __asm__(SYM("{name}"));')
        else:
            out.append(f'extern void {ident}(void) __asm__(SYM("{name}"));')
    out.append("")
    out += body
    dst = DST
    open(dst, "w").write("\n".join(out) + "\n")
    print(f"wrote {dst}: {len(refs)} references")


if __name__ == "__main__":
    main()
