#!/usr/bin/env python3
"""Generate src/psp/driver/cc-psp.r from the original exe: the string
resources RegisterCompilerResources (0x410420) registers.

    gen_cc_psp.py

Each table is an array of string pointers ending in NULL; the output has the
same form as mweppc's cc-eabi-ppc.r.
"""

import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOP = os.path.normpath(os.path.join(HERE, "..", ".."))
REPO = TOP
sys.path.insert(0, HERE)
from pe import PE  # noqa: E402

# (C name, table address): from RegisterCompilerResources
TABLES = [
    ("STR10000", 0x5C35B4),  # "Compiler Errors", 10000
    ("STR10001", 0x5C4048),  # "MIPS Compiler Errors", 10001
    ("STR10100", 0x5C3D58),  # "Compiler Strings", 10100
    ("STR13000", 0x5C41EC),  # "CmdLine Tool Strings", 13000
]


def cstring(pe, va):
    out = bytearray()
    while True:
        b = pe.read(va + len(out), 1)[0]
        if b == 0:
            return bytes(out)
        out.append(b)


def literal(b):
    s = []
    for c in b:
        ch = chr(c)
        if ch == "\\":
            s.append("\\\\")
        elif ch == '"':
            s.append('\\"')
        elif ch == "\n":
            s.append("\\n")
        elif ch == "\r":
            s.append("\\r")
        elif ch == "\t":
            s.append("\\t")
        elif 32 <= c < 127:
            s.append(ch)
        else:
            s.append(f"\\{c:03o}")
    return '"' + "".join(s) + '"'


def main():
    pe = PE(os.path.join(REPO, "orig", "PSP_3_0_1", "mwccpsp.exe"))
    lines = ["// generated by tools/mwccpsp/gen_cc_psp.py from the 3.0.1 exe: do not edit", ""]
    for name, va in TABLES:
        lines.append(f"static const char *{name}[] = {{")
        i = 0
        while True:
            p = struct.unpack("<I", pe.read(va + 4 * i, 4))[0]
            if p == 0:
                break
            lines.append(f"    {literal(cstring(pe, p))},")
            i += 1
        lines.append("    NULL")
        lines.append("};")
    out = os.path.join(TOP, "src", "psp", "driver", "cc-psp.r")
    open(out, "w").write("\n".join(lines) + "\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
