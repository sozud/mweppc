// 0x487F60: the mnemonic, lower case, with its ".suffix"es; a VFPU
// instruction whose format starts with '&' takes a ".xyzw" write mask
void func_00487F60(char* buf) {
    int i;
    AsmMnemonicRec* m;
    char* p;

    for (i = 0; tkidentifier->name[i]; i++) {
        buf[i] = tolower(tkidentifier->name[i]);
    }
    buf[i] = 0;

    data_00625EA1 = 0;
    data_00625ECD = 0;
    if ((m = func_0053E980(buf)) && data_006115F8[m->opcodes[0]].format[0] == '&') {
        if (lookahead() != '.') {
            data_00625EA1 = 0xF;
            return;
        }
        tk = lex();
        tk = lex();
        if (tk != TK_IDENTIFIER) {
            CError_Error(8);
        }
#if MWCCPS2
        // b210 (0x4945A0): an unknown letter is reported without advancing
        for (p = tkidentifier->name; *p;) {
            if (*p == 'x') {
                data_00625EA1 |= 8;
            } else if (*p == 'y') {
                data_00625EA1 |= 4;
            } else if (*p == 'z') {
                data_00625EA1 |= 2;
            } else if (*p == 'w') {
                data_00625EA1 |= 1;
            } else {
                CError_Error(8);
                continue;
            }
            p++;
        }
#else
        for (p = tkidentifier->name; *p; p++) {
            if (*p == 'x') {
                data_00625EA1 |= 8;
            } else if (*p == 'y') {
                data_00625EA1 |= 4;
            } else if (*p == 'z') {
                data_00625EA1 |= 2;
            } else if (*p == 'w') {
                data_00625EA1 |= 1;
            } else {
                CError_Error(8);
            }
        }
#endif
        return;
    }

    while (lookahead() == '.') {
        tk = lex();
        strcat(buf, ".");
        tk = lex();
        if (tk != TK_IDENTIFIER) {
            CError_Error(8);
        }
        for (i = 0; tkidentifier->name[i]; i++) {
            tkidentifier->name[i] = tolower(tkidentifier->name[i]);
        }
        strcat(buf, tkidentifier->name);
    }
}

